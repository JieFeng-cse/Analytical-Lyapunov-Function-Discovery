"""sympy -> Lean 4 (Mathlib `Real`) printer + HasDerivAt proof-term generator,
and the rotor2 fast-region export for the Lean project (lean/rotor-fl).

    python -m utils.fl_lean OUTDIR      # writes OUTDIR/FastDefs.lean, OUTDIR/FastDeriv.lean

Printer conventions: numbers are `(n : ℝ)` or ratios of them, integer powers
`^ n`, negative powers `/ (b ^ n)`, `Real.sin/cos/exp`. Fully parenthesised.

Proof terms: for `HasDerivAt (fun t => E(t)) E'(t₀) t₀` we emit the combinator
chain that mirrors E's tree (`.add`, `.mul`, `.pow`, `.sin`, `.cos`,
`hasDerivAt_id'`, `hasDerivAt_const`); the stated derivative is sympy's, and the
two are reconciled by the `deriv_tac` macro (congr_of_eventuallyEq + congr_deriv,
Pi-instance simp, norm_num, ring).
"""
import sys
from pathlib import Path

import sympy as sym


class LeanPrinter:
    def __init__(self, symmap):
        self.symmap = dict(symmap)

    def __call__(self, e):
        return self.p(sym.sympify(e))

    def num(self, e):
        if e.is_Integer:
            n = int(e)
            return f"({n} : ℝ)" if n >= 0 else f"(-({-n} : ℝ))"
        if e.is_Rational:
            p, q = int(e.p), int(e.q)
            return f"(({p} : ℝ) / ({q} : ℝ))" if p >= 0 else f"(-(({-p} : ℝ) / ({q} : ℝ)))"
        if e.is_Float:
            return self.num(sym.nsimplify(e, rational=True))
        raise ValueError(f"not a number: {e!r}")

    def p(self, e):
        if e.is_Symbol:
            return self.symmap[str(e)]
        if e.is_Number:
            return self.num(e)
        if e.is_Add:
            return "(" + " + ".join(self.p(a) for a in e.args) + ")"
        if e.is_Mul:
            return "(" + " * ".join(self.p(a) for a in e.args) + ")"
        if e.is_Pow:
            b, k = e.args
            if k.is_Integer:
                k = int(k)
                if k >= 0:
                    return f"({self.p(b)} ^ {k})"
                return f"((1 : ℝ) / ({self.p(b)} ^ {-k}))"
            raise ValueError(f"non-integer power: {e}")
        if isinstance(e, sym.sin):
            return f"(Real.sin {self.p(e.args[0])})"
        if isinstance(e, sym.cos):
            return f"(Real.cos {self.p(e.args[0])})"
        if isinstance(e, sym.exp):
            return f"(Real.exp {self.p(e.args[0])})"
        raise ValueError(f"unsupported node {type(e).__name__}: {e}")

    def hasderiv(self, e, var, pt):
        """Proof term of `HasDerivAt (fun var => e) _ pt` (value left to sympy)."""
        if e == var:
            return f"(hasDerivAt_id' {pt})"
        if var not in e.free_symbols:
            return f"(hasDerivAt_const {pt} {self.p(e)})"
        if e.is_Add:
            terms = [self.hasderiv(a, var, pt) for a in e.args]
            t = terms[0]
            for u in terms[1:]:
                t = f"({t}.add {u})"
            return t
        if e.is_Mul:
            terms = [self.hasderiv(a, var, pt) for a in e.args]
            t = terms[0]
            for u in terms[1:]:
                t = f"({t}.mul {u})"
            return t
        if e.is_Pow:
            b, k = e.args
            if k.is_Integer and int(k) >= 0:
                return f"({self.hasderiv(b, var, pt)}.pow {int(k)})"
            raise ValueError(f"unsupported power in derivative: {e}")
        if isinstance(e, sym.sin):
            return f"({self.hasderiv(e.args[0], var, pt)}.sin)"
        if isinstance(e, sym.cos):
            return f"({self.hasderiv(e.args[0], var, pt)}.cos)"
        if isinstance(e, sym.exp):
            return f"({self.hasderiv(e.args[0], var, pt)}.exp)"
        raise ValueError(f"unsupported node {type(e).__name__}: {e}")


def abs_bound_poly(expr, p1):
    """Bound |expr| by a polynomial in a = |p1|: coefficients of p1^k are
    trig polynomials in r; each is bounded by the sum of |numeric coeff| over
    its monomials (products of sin/cos powers are ≤ 1). Returns {k: bound}."""
    poly = sym.Poly(sym.expand(expr), p1)
    out = {}
    for (k,), coeff in poly.terms():
        total = 0
        for term in sym.Add.make_args(sym.expand(coeff)):
            c, rest = term.as_coeff_Mul()
            for f in sym.Mul.make_args(rest):
                b = f.base if f.is_Pow else f
                assert b == 1 or isinstance(b, (sym.sin, sym.cos)), (term, f)
            total += abs(c)
        out[k] = sym.nsimplify(total, rational=True)
    return out


HEADER = """/-
# {title} (GENERATED by utils/fl_lean.py — do not edit)
{blurb}
-/
import {imp}

namespace RotorFl

"""


def rotor2_fast_export():
    r, p1, p2, u = sym.symbols("x1 x2 x3 u")
    P = LeanPrinter({"x1": "r", "x2": "p₁", "x3": "p₂", "u": "u"})
    t = {
        1: sym.cos(r),
        2: p1 * sym.cos(r),
        3: p1**2 * sym.cos(r) + p1 * sym.sin(r) + sym.cos(r)**2,
        4: (-p1**3 * sym.cos(r) - 3 * p1**2 * sym.sin(r) - 3 * p1 * sym.cos(r)**2
            + p1 * sym.cos(r) - sym.Rational(1, 2) * sym.sin(r) * sym.cos(r) + 2 * sym.sin(r)),
    }
    subs = {"t": "t₁", 1: "t₁", 2: "t₂", 3: "t₃", 4: "t₄"}
    # ---------------- FastDefs.lean: derivative defs, c3..c5, bounds ----------
    defs = HEADER.format(title="Fast-region explicit derivatives",
                         blurb="Derivatives of the counterterms t₁..t₄ and the coefficients of\n"
                               "    L p̃f = c₃ u³ + c₄ u⁴ + c₅ u⁵,   u = 1/p₂   (ρ = 1),  c₃ = −1/2\n"
                               "with explicit polynomial bounds |c₄| ≤ c4_bound |p₁|, |c₅| ≤ c5_bound |p₁|.",
                         imp="RotorFl.Defs")
    deriv = {}
    for j, tj in t.items():
        deriv[j] = {"r": sym.expand(sym.diff(tj, r)), "p₁": sym.expand(sym.diff(tj, p1)),
                    "p₁p₁": sym.expand(sym.diff(tj, p1, 2))}
        for name, d in deriv[j].items():
            defs += f"/-- ∂_{name} t{j} -/\nnoncomputable def t{j}_{name} (r p₁ : ℝ) : ℝ := {P(d)}\n\n"
    pt = p2 - t[1] / p2 - t[2] / p2**2 - t[3] / p2**3 + t[4] / p2**4
    Lpt = (sym.diff(pt, r) * (p2 - p1) + sym.diff(pt, p1) * (sym.sin(r) - p1)
           + sym.diff(pt, p2) * (-sym.sin(r)) + sym.diff(pt, p1, 2))
    poly = sym.Poly(sym.expand(Lpt.subs(p2, 1 / u)), u)
    coeffs = {k: sym.expand(c) for (k,), c in poly.terms()}
    assert set(coeffs) == {3, 4, 5} and sym.simplify(coeffs[3]) == sym.Rational(-1, 2), coeffs
    defs += f"/-- coefficient of u³ in L p̃f (= −1/2 by sin² + cos² = 1) -/\nnoncomputable def c3 (r : ℝ) : ℝ := {P(coeffs[3])}\n\n"
    for k in (4, 5):
        defs += f"/-- coefficient of u^{k} in L p̃f -/\nnoncomputable def c{k} (r p₁ : ℝ) : ℝ := {P(coeffs[k])}\n\n"
        b = abs_bound_poly(coeffs[k], p1)
        bound = " + ".join(f"{P.num(v)} * |p₁| ^ {kk}" for kk, v in sorted(b.items()))
        defs += f"/-- |c{k}| ≤ this (triangle inequality, |sin|,|cos| ≤ 1) -/\nnoncomputable def c{k}_bound (p₁ : ℝ) : ℝ := {bound}\n\n"
    defs += "end RotorFl\n"
    # ---------------- FastDeriv.lean: HasDerivAt lemmas for t_j ---------------
    der = HEADER.format(title="Fast-region derivative lemmas",
                        blurb="`HasDerivAt` facts for t₁..t₄ and their p₁-derivatives, proof terms\n"
                              "generated from the expression trees.",
                        imp="RotorFl.FastDefs")
    der += "open Real\n\n"
    der += ("/-- Close `HasDerivAt (fun t => E t) E' t₀` from a combinator-chain proof whose\n"
            "function/value differ from the goal only by Pi-instance unfolding, casts and\n"
            "ring normalisation. -/\n"
            "macro \"deriv_tac\" h:term : tactic => `(tactic|\n"
            "  (refine (($h).congr_of_eventuallyEq (Filter.Eventually.of_forall fun x => ?_)).congr_deriv ?_ <;>\n"
            "    (try simp only [Pi.mul_apply, Pi.add_apply, Pi.pow_apply, Pi.sub_apply, Pi.neg_apply]) <;>\n"
            "    (try norm_num only) <;> ring))\n\n")
    for j, tj in t.items():
        # ∂_r t_j at r
        der += (f"lemma hasDerivAt_t{j}_r (r p₁ : ℝ) : HasDerivAt (fun t => {subs[j]} t p₁) (t{j}_r r p₁) r := by\n"
                f"  unfold {subs[j]} t{j}_r\n  deriv_tac {P.hasderiv(tj, r, 'r')}\n\n")
        # ∂_p₁ t_j at p₁
        der += (f"lemma hasDerivAt_t{j}_p₁ (r p₁ : ℝ) : HasDerivAt (fun t => {subs[j]} r t) (t{j}_p₁ r p₁) p₁ := by\n"
                f"  unfold {subs[j]} t{j}_p₁\n  deriv_tac {P.hasderiv(tj, p1, 'p₁')}\n\n")
        # ∂_p₁ (∂_p₁ t_j) at p₁
        der += (f"lemma hasDerivAt_t{j}_p₁p₁ (r p₁ : ℝ) : HasDerivAt (fun t => t{j}_p₁ r t) (t{j}_p₁p₁ r p₁) p₁ := by\n"
                f"  unfold t{j}_p₁ t{j}_p₁p₁\n  deriv_tac {P.hasderiv(deriv[j]['p₁'], p1, 'p₁')}\n\n")
    der += "end RotorFl\n"
    # ---------------- FastBounds.lean: |trig poly| ≤ poly(|p₁|) lemmas ---------
    bnd = HEADER.format(title="Fast-region absolute-value bounds",
                        blurb="`|E r p₁| ≤ Σ B_k |p₁|^k` for the trig polynomials E used in the\n"
                              "fast-region estimate; each monomial is bounded by `abs_mono_le`, the sum\n"
                              "by `linarith`.",
                        imp="RotorFl.Bounds\nimport RotorFl.FastDefs")
    bnd += "open Real\n\n"

    def bound_lemma(lean_name, expr, unfold):
        """|lean_name r p₁| ≤ bound, proof by per-monomial abs_mono_le + linarith."""
        e = sym.expand(expr)
        if e == 0:
            return (f"lemma abs_{lean_name}_le (r p₁ : ℝ) : |{unfold} r p₁| ≤ (0 : ℝ) := by\n"
                    f"  unfold {unfold}\n  simp\n\n")
        b = abs_bound_poly(e, p1)
        bound = " + ".join(f"{P.num(v)} * |p₁| ^ {kk}" for kk, v in sorted(b.items())) or "(0 : ℝ)"
        out = f"lemma abs_{lean_name}_le (r p₁ : ℝ) : |{unfold} r p₁| ≤ {bound} := by\n  unfold {unfold}\n"
        haves = []
        for n, term in enumerate(sym.Add.make_args(e)):
            c, rest = term.as_coeff_Mul()
            k = i = j = 0
            for f in sym.Mul.make_args(rest):
                base, ex = (f.base, int(f.exp)) if f.is_Pow else (f, 1)
                if base == p1:
                    k = ex
                elif isinstance(base, sym.sin):
                    i = ex
                elif isinstance(base, sym.cos):
                    j = ex
                elif base == 1:
                    pass
                else:
                    raise ValueError(f"unexpected factor {f} in {term}")
            out += (f"  have h{n} := abs_le.mp (abs_mono_le {P.num(c)} {P.num(abs(c))} p₁ (Real.sin r) (Real.cos r) "
                    f"{k} {i} {j} (by norm_num) (abs_sin_le_one r) (abs_cos_le_one r))\n")
            haves.append(f"h{n}")
        hs = ", ".join(f"{h}.1, {h}.2" for h in haves)
        out += f"  exact abs_le.mpr ⟨by linarith [{hs}], by linarith [{hs}]⟩\n\n"
        return out

    for j, tj in t.items():
        bnd += bound_lemma(f"t{j}", tj, subs[j])
        bnd += bound_lemma(f"t{j}_r", deriv[j]["r"], f"t{j}_r")
        bnd += bound_lemma(f"t{j}_p₁", deriv[j]["p₁"], f"t{j}_p₁")
        bnd += bound_lemma(f"t{j}_p₁p₁", deriv[j]["p₁p₁"], f"t{j}_p₁p₁")
    bnd += bound_lemma("c4", coeffs[4], "c4")
    bnd += bound_lemma("c5", coeffs[5], "c5")
    bnd += "end RotorFl\n"
    return {"FastDefs.lean": defs, "FastDeriv.lean": der, "FastBounds.lean": bnd}, coeffs


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    files, _ = rotor2_fast_export()
    for name, text in files.items():
        if out is None:
            print(f"===== {name}\n{text}")
        else:
            (out / name).write_text(text)
            print(f"wrote {out / name}")
